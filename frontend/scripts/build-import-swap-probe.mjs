#!/usr/bin/env node
/**
 * Compiles api/lib/importSwapProbe/ImportSwapProbe.sol (solc from the repo root, the same compiler
 * family as hardhat) and writes its runtime bytecode + ABI to importSwapProbeArtifact.js. The probe
 * is never deployed: the scanner places the runtime code at a throwaway address in an eth_call.
 *
 *   node scripts/build-import-swap-probe.mjs          write the artifact
 *   node scripts/build-import-swap-probe.mjs --check  fail if the committed artifact is stale
 */
import fs from "node:fs";
import path from "node:path";
import { createRequire } from "node:module";
import { fileURLToPath } from "node:url";

const here = path.dirname(fileURLToPath(import.meta.url));
const dir = path.resolve(here, "../api/lib/importSwapProbe");
const require = createRequire(path.resolve(here, "../../package.json"));
const solc = require("solc");

const source = fs.readFileSync(path.join(dir, "ImportSwapProbe.sol"), "utf8");
const output = JSON.parse(solc.compile(JSON.stringify({
  language: "Solidity",
  sources: { "ImportSwapProbe.sol": { content: source } },
  settings: {
    optimizer: { enabled: true, runs: 200 },
    evmVersion: "paris", // no PUSH0: runs on every EVM chain we scan
    outputSelection: { "*": { ImportSwapProbe: ["abi", "evm.deployedBytecode.object"] } },
  },
})));
const errors = (output.errors || []).filter((e) => e.severity === "error");
if (errors.length) {
  console.error(errors.map((e) => e.formattedMessage).join("\n"));
  process.exit(1);
}
const contract = output.contracts["ImportSwapProbe.sol"].ImportSwapProbe;
const artifact = `// Generated by scripts/build-import-swap-probe.mjs (solc ${solc.version()}). Do not edit.
export const IMPORT_SWAP_PROBE_ABI = ${JSON.stringify(contract.abi)};
export const IMPORT_SWAP_PROBE_RUNTIME = "0x${contract.evm.deployedBytecode.object}";
`;
const target = path.join(dir, "importSwapProbeArtifact.js");
if (process.argv.includes("--check")) {
  const current = fs.existsSync(target) ? fs.readFileSync(target, "utf8") : "";
  if (current !== artifact) {
    console.error("importSwapProbeArtifact.js is stale: run node scripts/build-import-swap-probe.mjs");
    process.exit(1);
  }
  console.log("importSwapProbeArtifact.js matches ImportSwapProbe.sol");
} else {
  fs.writeFileSync(target, artifact);
  console.log(`wrote ${path.relative(process.cwd(), target)} (${contract.evm.deployedBytecode.object.length / 2} bytes runtime)`);
}
