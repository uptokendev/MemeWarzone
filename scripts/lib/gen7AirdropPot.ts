/** The first week end (Monday 00:00 UTC, >= the last ended one) whose gen-7 trader + creator ids are authorized. */
export async function firstAuthorizedGen7WeekEnd(chainId: number, distributor: string, nowSec: number): Promise<number | null> {
  const { weeklyContractBatchId } = await esm("frontend/scripts/weekly-airdrop/materialize.mjs");
  const d = distAt(distributor);
  const end0 = utcEpochEnd(nowSec);
  for (let w = 0; w <= 26; w++) {
    const end = end0 + w * WEEK;
    let ok = true;
    for (const p of AIRDROP_PROGRAMS) {
      const a = await d.batchAuthorization(weeklyContractBatchId(chainId, epochIdForEnd(end), p, GEN7_POT));
      if (!a.authorized || a.consumed) ok = false;
    }
    if (ok) return end;
  }
  return null;
}

/** A minimal pg-client stand-in: remembers the rows the runner writes, returns them where it reads them back. */
function fakeClient() {
  const batches = new Map<string, any>();
  const ledger: any[] = [];
  const queries: string[] = [];
  const client = {
    async query(sql: string, params: any[] = []) {
      const s = String(sql).replace(/\s+/g, " ").trim();
      queries.push(s.slice(0, 80));
      if (/^insert into public\.reward_batches/i.test(s)) {
        const row = { id: crypto.randomUUID(), status: "funding_check", total_amount: params[1], metadata: JSON.parse(params[3]) };
        batches.set(row.id, row);
        return { rows: [row] };
      }
      if (/^update public\.reward_batches set metadata=coalesce\(metadata,'\{\}'::jsonb\)\|\|\$2::jsonb,updated_at=now\(\) where id=\$1::uuid returning \*/i.test(s)) {
        const row = batches.get(params[0]);
        row.metadata = { ...row.metadata, ...JSON.parse(params[1]) };
        return { rows: [row] };
      }
      if (/^update public\.reward_batches set status='claim_open'/i.test(s)) {
        const row = batches.get(params[0]);
        row.status = "claim_open";
        row.metadata = { ...row.metadata, ...JSON.parse(params[2]) };
        return { rows: [row] };
      }
      if (/^insert into public\.reward_ledger/i.test(s)) {
        const row = { id: crypto.randomUUID(), source_id: params[0], wallet_address: params[1], amount: params[3], metadata: JSON.parse(params[4]) };
        ledger.push(row);
        return { rows: [row] };
      }
      return { rows: [] };
    },
  };
  return { client, batches, ledger, queries };
}

/**
 * A local HTTP server: `/rpc` forwards JSON-RPC to hardhat's provider (so chain.mjs's JsonRpcProvider reads the
 * fork), `/fund` is the funding executor the runner calls when no operator key is set.
 */
async function startLocalBridge(onFund: (payload: any) => Promise<any>) {
  const server = http.createServer((req, res) => {
    let body = "";
    req.on("data", (c) => (body += c));
    req.on("end", async () => {
      const reply = (code: number, obj: unknown) => {
        res.writeHead(code, { "content-type": "application/json" });
        res.end(JSON.stringify(obj, (_k, v) => (typeof v === "bigint" ? v.toString() : v)));
      };
      try {
        const parsed = JSON.parse(body || "{}");
        if (req.url === "/fund") return reply(200, await onFund(parsed));
        const one = async (r: any) => {
          try {
            return { jsonrpc: "2.0", id: r.id, result: await network.provider.send(r.method, r.params || []) };
          } catch (e: any) {
            return { jsonrpc: "2.0", id: r.id, error: { code: -32000, message: String(e?.message || e), data: e?.data } };
          }
        };
        reply(200, Array.isArray(parsed) ? await Promise.all(parsed.map(one)) : await one(parsed));
      } catch (e: any) {
        reply(500, { ok: false, error: String(e?.message || e) });
      }
    });
  });
  await new Promise<void>((r) => server.listen(0, "127.0.0.1", () => r()));
  const port = (server.address() as any).port;
  return { url: `http://127.0.0.1:${port}`, close: () => new Promise<void>((r) => server.close(() => r())) };
}

/** Runs `fn` with chain.mjs pointed at the fork through the local bridge (env restored afterwards). */
export async function withRunnerEnv<T>(chainId: number, extra: Record<string, string | undefined>, onFund: (payload: any) => Promise<any>, fn: (bridgeUrl: string) => Promise<T>): Promise<T> {
  const bridge = await startLocalBridge(onFund);
  const keys = [`BSC_RPC_HTTP_${chainId}`, "BSC_RPC_HTTP", "RPC_URL", `AIRDROP_OPERATOR_PRIVATE_KEY_${chainId}`, `AIRDROP_OPERATOR_PRIVATE_KEY_GEN7_${chainId}`, "REWARD_FUNDING_EXECUTOR_URL", "REWARD_FUNDING_EXECUTOR_TOKEN", "AIRDROP_ALLOW_CROSS_PROGRAM_WINNERS", "AIRDROP_TRADER_WINNERS", "AIRDROP_CREATOR_WINNERS", "AIRDROP_MAX_WINNERS_PER_PROGRAM", "AIRDROP_TARGET_PAYOUT_WEI", "AIRDROP_AUTH_ALERT_WEEKS", ...Object.keys(extra)];
  const saved = Object.fromEntries(keys.map((k) => [k, process.env[k]]));
  for (const k of keys) delete process.env[k];
  Object.assign(process.env, { [`BSC_RPC_HTTP_${chainId}`]: `${bridge.url}/rpc`, REWARD_FUNDING_EXECUTOR_URL: `${bridge.url}/fund`, REWARD_FUNDING_EXECUTOR_TOKEN: "local-rehearsal" });
  for (const [k, v] of Object.entries(extra)) if (v !== undefined) process.env[k] = v;
  try {
    return await fn(bridge.url);
  } finally {
    for (const [k, v] of Object.entries(saved)) {
      if (v === undefined) delete process.env[k];
      else process.env[k] = v;
    }
    await bridge.close();
  }
}

