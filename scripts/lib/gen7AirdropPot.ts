/**
 * One weekly gen-7 draw on the fork through potRun.runPot: the week that ended on the last Monday (call it after
 * that Monday's 00:00 UTC, inside the authorized publish window), traders and creators given by the caller (the
 * rehearsal's own trading wallets stand in for the DB's candidate query), funded from the gen-7 vault by `fundAs`.
 */
export async function runGen7AirdropWeek(opts: {
  chainId: number;
  vault: string;
  distributor: string;
  mainVault: string;
  mainDistributor: string | null;
  traders: string[];
  creators: string[];
  fundAs: any;
  nativeUsd: number;
  distributionBps?: number;
}): Promise<Gen7AirdropWeekResult> {
  const potRun = await esm("frontend/scripts/weekly-airdrop/potRun.mjs");
  const config = await esm("frontend/scripts/weekly-airdrop/config.mjs");
  const { weeklyContractBatchId } = await esm("frontend/scripts/weekly-airdrop/materialize.mjs");
  const nowSec = Number((await ethers.provider.getBlock("latest"))!.timestamp);
  const { start, end, epochId } = config.epochWindow(new Date(nowSec * 1000));
  const claimDeadline = Math.floor(end.getTime() / 1000) + 7 * DAY; // AIRDROP_CLAIM_WINDOW_DAYS default 7
  const drawSecret = crypto.randomBytes(32).toString("hex");
  const distributionBps = opts.distributionBps ?? 5000;
  const vault = new ethers.Contract(opts.vault, COMMUNITY_VAULT_ABI, ethers.provider);
  const readMain = async () => ({
    vault: BigInt(await new ethers.Contract(opts.mainVault, COMMUNITY_VAULT_ABI, ethers.provider).warzoneAirdropBalance()),
    distBalance: opts.mainDistributor ? await ethers.provider.getBalance(opts.mainDistributor) : 0n,
    outstanding: opts.mainDistributor ? BigInt(await distAt(opts.mainDistributor).totalOutstandingRewards()) : 0n,
  });
  const mainBefore = await readMain();
  const vaultBefore = BigInt(await vault.warzoneAirdropBalance());
  const fundRequests: any[] = [];
  const fundTxs: string[] = [];
  const alerts: any[] = [];
  const fake = fakeClient();

  const onFund = async (payload: any) => {
    fundRequests.push(payload);
    if (payload.action !== "fund_airdrop_batch" || payload.functionName !== "fundAirdropBatch" || !same(payload.targetContract, opts.vault) || Number(payload.chainId) !== opts.chainId || !same(payload.distributorAddress, opts.distributor)) {
      return { ok: false, error: "unexpected funding request" };
    }
    const [batchId, root, deadline, amount] = payload.args;
    const tx = await (vault.connect(opts.fundAs) as any).fundAirdropBatch(batchId, root, BigInt(deadline), BigInt(amount));
    const rc = await tx.wait();
    fundTxs.push(tx.hash);
    return { ok: true, txHash: tx.hash, blockNumber: rc.blockNumber, requestId: `local-${fundTxs.length}` };
  };

  const toCandidate = (w: string, i: number) => ({ walletAddress: ethers.getAddress(w), finalWeight: 1 + i * 0.1, activityScore: 1, reasonCodes: ["rehearsal"], totalVolumeRaw: "0", countedVolumeRaw: "0" });
  await withRunnerEnv(opts.chainId, { [`AIRDROP_NATIVE_USD_${opts.chainId}`]: String(opts.nativeUsd) }, onFund, async () => {
    const ctx = { chainId: opts.chainId, epochId, start, end, claimDeadline, commitment: config.seedCommitment(drawSecret, opts.chainId, epochId), drawSecret, dryRun: false, distributionBps };
    await potRun.runPot(fake.client, ctx, { pot: GEN7_POT, label: "gen-7 pot", vaultAddress: ethers.getAddress(opts.vault), distributorAddress: ethers.getAddress(opts.distributor) }, new Set(), {
      // The DB-only steps (the rest is the runner's own code against the fork).
      findEpochBatch: async () => null,
      otherPotWallets: async () => [],
      exclusionSets: async () => ({ all: new Set(), totalCount: 0 }),
      traderCandidates: async () => opts.traders.map(toCandidate),
      creatorCandidates: async () => opts.creators.map(toCandidate),
      stageWinners: async () => {},
      writeRewardAlert: async (_c: any, a: any) => { alerts.push(a); },
    });
  });

  const vaultAfter = BigInt(await vault.warzoneAirdropBalance());
  const dist = distAt(opts.distributor);
  const mainDist = opts.mainDistributor ? distAt(opts.mainDistributor) : null;
  const batches: Gen7AirdropWeekResult["batches"] = [];
  for (const b of fake.batches.values()) {
    const m = b.metadata;
    const rows = fake.ledger.filter((l) => l.metadata.batchId === b.id);
    const onChain = await dist.batches(m.contractBatchId);
    batches.push({
      program: m.program,
      contractBatchId: m.contractBatchId,
      expectedId: weeklyContractBatchId(opts.chainId, epochId, m.program, GEN7_POT),
      merkleRoot: m.merkleRoot,
      total: BigInt(m.merkleTotalAmount),
      winners: rows.map((r) => ({ wallet: ethers.getAddress(r.wallet_address), amount: BigInt(r.metadata.claimAmount), proof: r.metadata.merkleProof })),
      onChain: { totalFunded: BigInt(onChain.totalFunded), exists: Boolean(onChain.exists), claimDeadline: BigInt(onChain.claimDeadline) },
      mainHasIt: mainDist ? Boolean((await mainDist.batches(m.contractBatchId)).exists) : false,
      status: b.status,
    });
  }
  return {
    epochId, vaultBefore, vaultAfter, distributionBps, batches, fundRequests, fundTxs, alerts,
    funded: batches.reduce((s, b) => s + b.onChain.totalFunded, 0n),
    main: { before: mainBefore, after: await readMain() },
  };
}

/** A winner claims from the gen-7 distributor; returns the native received (gas excluded) and the main pot's answer. */
export async function claimGen7Win(opts: { distributor: string; mainDistributor: string | null; batchId: string; winner: { wallet: string; amount: bigint; proof: string[] }; signer: any }) {
  const dist = new ethers.Contract(opts.distributor, DISTRIBUTOR_ABI, opts.signer);
  let mainRefusal: string | null = null;
  if (opts.mainDistributor) {
    try {
      await new ethers.Contract(opts.mainDistributor, ["function claim(bytes32,uint256,bytes32[])", "error BatchMissing(bytes32)"], opts.signer).claim.staticCall(opts.batchId, opts.winner.amount, opts.winner.proof);
      mainRefusal = "NO_REVERT";
    } catch (e: any) {
      mainRefusal = e?.revert?.name || String(e?.shortMessage || e?.message || e).split("\n")[0];
    }
  }
  const before = await ethers.provider.getBalance(opts.winner.wallet);
  const rc = await (await dist.claim(opts.batchId, opts.winner.amount, opts.winner.proof)).wait();
  const after = await ethers.provider.getBalance(opts.winner.wallet);
  const gas = BigInt(rc.gasUsed) * BigInt(rc.gasPrice ?? 0n);
  return { received: after - before + gas, gas: rc.gasUsed, tx: rc.hash, claimed: await dist.hasClaimed(opts.batchId, opts.winner.wallet), mainRefusal };
}

type CheckFn = (name: string, pass: boolean, proof: Record<string, unknown>) => void;

/**
 * The gen-7 pot's acceptance after its wiring batch ran, shared by the two mainnet-fork rehearsals and the two
 * testnet lifecycle scripts:
 *   1. wiring read back + the runner's runway check as it will run on the first authorized Monday: 12 weeks
 *   2. one weekly draw through potRun.runPot funded from the gen-7 vault (the rehearsal's trades filled it) by the
 *      vault's airdrop operator (impersonated on a fork); ids = the runner's gen-7 ids; the main pot untouched
 *   3. a winner claims from the gen-7 distributor (the main distributor does not know the batch)
 * On a fork time is warped to the first authorized Monday + 15 min (the runner's slot). On a real testnet (no warp)
 * the admin authorizes the week that just ended with the runner's id (testnet only: the deployer is the owner there).
 */
export async function rehearseGen7AirdropPot(opts: {
  chainId: number;
  vault: string;
  setup: Gen7AirdropSetup;
  admin: string;
  traders: any[];
  creators: any[];
  nativeUsd: number;
  check: CheckFn;
  fork: boolean;
  testnetAdminSigner?: any;
  symbol: string;
}) {
  const { chainId, vault, setup, check } = opts;
  const nowSec = Number((await ethers.provider.getBlock("latest"))!.timestamp);
  const pot = await readGen7AirdropPot({ chainId, vault, setup, admin: opts.admin });
  const firstEnd = await firstAuthorizedGen7WeekEnd(chainId, setup.distributor, nowSec);
  check(`gen-7 airdrop pot wired by the admin batch: community vault -> its own airdrop distributor, airdrop operator = the main pot's (${setup.operatorSource}), distributor batchOperator = the gen-7 community vault, owner = admin`, pot.wired && firstEnd !== null, { ...pot, distributor: setup.distributor, cap: setup.cap, capSource: setup.capSource, firstAuthorizedWeekEnd: firstEnd ? new Date(firstEnd * 1000).toISOString() : null });
  const runAt = firstEnd! + 900;
  const pots = [{ pot: GEN7_POT, distributorAddress: setup.distributor }, ...(setup.mainDistributor ? [{ pot: "main", distributorAddress: setup.mainDistributor }] : [])];
  const runway = (await runnerRunway({ chainId, pots, nowSec: runAt })) as any[];
  const g = runway.find((r) => r.pot === GEN7_POT);
  const m = runway.find((r) => r.pot === "main");
  check("runner runway check (authorizationHorizon.mjs) on the first authorized Monday: the gen-7 pot has 12 weeks pre-authorized, verdict ok", g?.runway?.coveredWeeks === GEN7_AIRDROP_WEEKS && g?.verdict?.level === "ok", { gen7: { coveredWeeks: g?.runway?.coveredWeeks, from: g?.runway?.currentEpochId, through: g?.runway?.lastCoveredEpochId, verdict: g?.verdict?.level }, main: m ? { coveredWeeks: m.runway?.coveredWeeks, verdict: m.verdict?.level, error: m.error } : null });

  // Into the draw window.
  if (opts.fork) {
    const now = Number((await ethers.provider.getBlock("latest"))!.timestamp);
    if (runAt > now) {
      await network.provider.send("evm_increaseTime", [runAt - now]);
      await network.provider.send("evm_mine", []);
    }
  } else if (Number((await ethers.provider.getBlock("latest"))!.timestamp) < firstEnd!) {
    if (!opts.testnetAdminSigner || chainId === 56 || chainId === 4663) throw new Error("no warp on a live chain: the gen-7 draw waits for its first authorized Monday");
    const { weeklyContractBatchId } = await esm("frontend/scripts/weekly-airdrop/materialize.mjs");
    const now = Number((await ethers.provider.getBlock("latest"))!.timestamp);
    const end = utcEpochEnd(now);
    const d = new ethers.Contract(setup.distributor, DISTRIBUTOR_ABI, opts.testnetAdminSigner);
    for (const p of AIRDROP_PROGRAMS) {
      const id = weeklyContractBatchId(chainId, epochIdForEnd(end), p, GEN7_POT);
      const a = await d.batchAuthorization(id);
      if (!a.authorized && !a.consumed) await (await d.authorizeBatch(id, setup.cap, end, Math.max(end + 6 * DAY, now + 3600))).wait();
    }
    console.log(`[gen7-airdrop] testnet: the admin authorized the week ending ${new Date(end * 1000).toISOString()} (runner ids) so the draw runs now`);
  }

  const operator = ethers.getAddress(setup.operator);
  let fundAs: any;
  if (opts.fork) {
    await network.provider.send("hardhat_impersonateAccount", [operator]);
    await network.provider.send("hardhat_setBalance", [operator, ethers.toQuantity(ethers.parseEther("1"))]);
    fundAs = await ethers.getSigner(operator);
  } else {
    fundAs = opts.testnetAdminSigner; // testnet: the admin may fund (onlyAdminOrAirdropOperator)
  }
  const signers = new Map<string, any>([...opts.traders, ...opts.creators].map((w) => [ethers.getAddress(w.address), w]));
  let week: Gen7AirdropWeekResult;
  try {
    week = await runGen7AirdropWeek({ chainId, vault, distributor: setup.distributor, mainVault: setup.mainVault, mainDistributor: setup.mainDistributor, traders: opts.traders.map((w) => w.address), creators: opts.creators.map((w) => w.address), fundAs, nativeUsd: opts.nativeUsd });
  } finally {
    if (opts.fork) await network.provider.send("hardhat_stopImpersonatingAccount", [operator]);
  }
  const pool = (week.vaultBefore * BigInt(week.distributionBps)) / 10_000n;
  const fmt = (v: bigint) => `${ethers.formatEther(v)} ${opts.symbol}`;
  check(`weekly gen-7 draw through the runner (potRun.runPot -> materialize -> chain.mjs ensureOnChainBatch): trader + creator batches funded from the gen-7 vault by its airdrop operator, ids = weeklyContractBatchId(.., "gen7"), funded = ${week.distributionBps / 100}% of the vault, claim-open`,
    week.batches.length === 2 && week.batches.every((b) => b.contractBatchId === b.expectedId && b.onChain.exists && b.onChain.totalFunded === b.total && b.status === "claim_open" && !b.mainHasIt && b.winners.length > 0) &&
      week.funded === pool && week.vaultBefore - week.vaultAfter === week.funded && week.fundTxs.length === 2 && week.fundRequests.every((r) => same(r.targetContract, vault)) && week.alerts.length === 0,
    { epochId: week.epochId, vaultBefore: fmt(week.vaultBefore), funded: fmt(week.funded), vaultAfter: fmt(week.vaultAfter), fundedBy: fundAs.address ?? (await fundAs.getAddress()), batches: week.batches.map((b) => ({ program: b.program, id: b.contractBatchId, total: fmt(b.total), winners: b.winners.map((w) => `${w.wallet}=${fmt(w.amount)}`) })), fundTxs: week.fundTxs, alerts: week.alerts });

  const trader = week.batches.find((b) => b.program === "airdrop_trader")!;
  const winner = trader.winners[0];
  const claim = await claimGen7Win({ distributor: setup.distributor, mainDistributor: setup.mainDistributor, batchId: trader.contractBatchId, winner, signer: signers.get(winner.wallet) });
  const mainSame = week.main.before.vault === week.main.after.vault && week.main.before.distBalance === week.main.after.distBalance && week.main.before.outstanding === week.main.after.outstanding;
  check("a gen-7 winner claims from the gen-7 distributor (exact amount, by balance delta); the main distributor does not know the batch; the main pot (vault balance, distributor balance, outstanding) untouched",
    claim.received === winner.amount && claim.claimed && (setup.mainDistributor ? claim.mainRefusal !== "NO_REVERT" : true) && mainSame,
    { winner: winner.wallet, amount: fmt(winner.amount), received: fmt(claim.received), tx: claim.tx, mainDistributorClaim: claim.mainRefusal, main: { before: { vault: fmt(week.main.before.vault), distributor: fmt(week.main.before.distBalance), outstanding: fmt(week.main.before.outstanding) }, after: { vault: fmt(week.main.after.vault), distributor: fmt(week.main.after.distBalance), outstanding: fmt(week.main.after.outstanding) } } });
  return { epochId: week.epochId, vaultBefore: week.vaultBefore, funded: week.funded, batches: week.batches, claim, runway: { gen7: g?.runway, main: m?.runway } };
}
