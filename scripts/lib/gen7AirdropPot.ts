/** Deploys the gen-7 airdrop RewardDistributor (owner = admin) and reads the owner back. */
export async function deployGen7AirdropDistributor(deployer: any, admin: string): Promise<{ address: string; block: number }> {
  const dist = await (await ethers.getContractFactory("RewardDistributor", deployer)).deploy(admin);
  await dist.waitForDeployment();
  const address = ethers.getAddress(await dist.getAddress());
  const owner = await new ethers.Contract(address, DISTRIBUTOR_ABI, ethers.provider).owner();
  if (!same(owner, admin)) throw new Error(`gen-7 airdrop distributor ${address} owner ${owner} != ${admin}`);
  const block = Number((await dist.deploymentTransaction()?.wait())?.blockNumber ?? 0);
  return { address, block };
}

/** The main pot of a chain: the live router's CommunityRewardsVault, its distributor and airdrop operator. */
export async function readMainAirdropPot(mainVault: string) {
  const v = new ethers.Contract(mainVault, COMMUNITY_VAULT_ABI, ethers.provider);
  const [distributor, operator] = await Promise.all([v.rewardDistributor(), v.airdropOperator()]);
  return {
    vault: ethers.getAddress(mainVault),
    distributor: isZero(distributor) ? null : ethers.getAddress(distributor),
    operator: isZero(operator) ? null : ethers.getAddress(operator),
  };
}

function utcEpochEnd(nowSec: number): number {
  // epochWindow(): the Monday 00:00 UTC that ends the last full week (<= now).
  const d = new Date(nowSec * 1000);
  const day = d.getUTCDay();
  d.setUTCDate(d.getUTCDate() + (day === 0 ? -6 : 1 - day));
  d.setUTCHours(0, 0, 0, 0);
  return Math.floor(d.getTime() / 1000);
}
const epochIdForEnd = (endSec: number) => new Date((endSec - WEEK) * 1000).toISOString().slice(0, 10);

/** The main pot's per-batch cap, as the Safe authorizes it today. */
export async function mainAirdropCap(opts: { chainId: number; mainDistributor: string | null; recordChainIds?: number[] }): Promise<{ cap: bigint; source: string }> {
  const env = String(process.env.GEN7_AIRDROP_CAP || "").trim();
  if (env) {
    const cap = ethers.parseEther(env);
    if (cap <= 0n) throw new Error("GEN7_AIRDROP_CAP must be positive");
    return { cap, source: `env GEN7_AIRDROP_CAP=${env}` };
  }
  const { weeklyContractBatchId } = await esm("frontend/scripts/weekly-airdrop/materialize.mjs");
  const nowSec = Number((await ethers.provider.getBlock("latest"))!.timestamp);
  if (opts.mainDistributor) {
    const d = distAt(opts.mainDistributor);
    // Latest authorized main-pot week: scan from 8 weeks back to 26 ahead, keep the last one found.
    let found: { cap: bigint; epochId: string } | null = null;
    const end0 = utcEpochEnd(nowSec);
    for (let w = -8; w <= 26; w++) {
      const epochId = epochIdForEnd(end0 + w * WEEK);
      for (const program of AIRDROP_PROGRAMS) {
        const a = await d.batchAuthorization(weeklyContractBatchId(opts.chainId, epochId, program));
        if (a.authorized || a.consumed) found = { cap: BigInt(a.maxAmount), epochId };
      }
    }
    if (found && found.cap > 0n) return { cap: found.cap, source: `main distributor ${opts.mainDistributor} batchAuthorization(${found.epochId}).maxAmount on chain ${opts.chainId}` };
  }
  // Records: the last authorizeBatch in the repo's Safe batches on the main distributor (or, for a testnet whose
  // main pot was never authorized, on the mainnet main distributor it mirrors).
  const dirs: Record<number, string> = { 56: "bnb", 4663: "robinhood", 97: "bscTestnet", 46630: "robinhood" };
  for (const chainId of opts.recordChainIds ?? [opts.chainId]) {
    const dir = path.join(ROOT, "deployments", dirs[chainId] || "");
    if (!fs.existsSync(dir)) continue;
    let last: { cap: bigint; file: string; publishAfter: bigint } | null = null;
    for (const f of fs.readdirSync(dir).filter((n) => n.endsWith(".safe-batch.json"))) {
      const batch = JSON.parse(fs.readFileSync(path.join(dir, f), "utf8"));
      if (Number(batch.chainId) !== chainId) continue;
      const mainDistributor = chainId === opts.chainId ? opts.mainDistributor : null;
      for (const tx of batch.transactions || []) {
        if (tx.contractMethod?.name !== "authorizeBatch") continue;
        if (mainDistributor && !same(tx.to, mainDistributor)) continue;
        const v = tx.contractInputsValues || {};
        const id = String(v.batchId || "");
        const epochId = new Date((Number(v.publishAfter) - WEEK) * 1000).toISOString().slice(0, 10);
        const isAirdropId = AIRDROP_PROGRAMS.some((p) => weeklyContractBatchId(chainId, epochId, p) === id);
        if (!isAirdropId) continue;
        if (!last || BigInt(v.publishAfter) >= last.publishAfter) last = { cap: BigInt(v.maxAmount), file: f, publishAfter: BigInt(v.publishAfter) };
      }
    }
    if (last && last.cap > 0n) return { cap: last.cap, source: `deployments/${dirs[chainId]}/${last.file} (last main-pot authorizeBatch on chain ${chainId})` };
  }
  throw new Error(`no main-pot airdrop authorization found for chain ${opts.chainId}; set GEN7_AIRDROP_CAP (native units)`);
}

function distAt(address: string) {
  return new ethers.Contract(address, DISTRIBUTOR_ABI, ethers.provider);
}

export type Gen7AirdropSetup = {
  distributor: string;
  mainVault: string;
  mainDistributor: string | null;
  operator: string;
  operatorSource: string;
  cap: string;
  capSource: string;
  weeks: number;
};

/**
 * Operator + cap for the gen-7 pot, read from the main pot. Mainnet refuses a main vault without an airdrop
 * operator (the runner key would have nothing to fund with); a testnet falls back to its admin (the deployer).
 */
export async function resolveGen7AirdropSetup(opts: { chainId: number; mainVault: string; distributor: string; testnetAdmin?: string }): Promise<Gen7AirdropSetup> {
  const main = await readMainAirdropPot(opts.mainVault);
  const envOp = String(process.env.GEN7_AIRDROP_OPERATOR || "").trim();
  let operator: string;
  let operatorSource: string;
  if (envOp) {
    operator = ethers.getAddress(envOp);
    operatorSource = "env GEN7_AIRDROP_OPERATOR";
  } else if (main.operator) {
    operator = main.operator;
    operatorSource = `main vault ${main.vault}.airdropOperator()`;
  } else if (opts.testnetAdmin) {
    operator = ethers.getAddress(opts.testnetAdmin);
    operatorSource = `testnet: main vault ${main.vault} has no airdropOperator; the admin (deployer)`;
  } else {
    throw new Error(`main CommunityRewardsVault ${main.vault} has no airdropOperator on chain ${opts.chainId}; set GEN7_AIRDROP_OPERATOR or wire the main pot first`);
  }
  const mirror: Record<number, number> = { 97: 56, 46630: 4663 };
  const { cap, source } = await mainAirdropCap({ chainId: opts.chainId, mainDistributor: main.distributor, recordChainIds: mirror[opts.chainId] ? [opts.chainId, mirror[opts.chainId]] : [opts.chainId] });
  return { distributor: ethers.getAddress(opts.distributor), mainVault: main.vault, mainDistributor: main.distributor, operator, operatorSource, cap: cap.toString(), capSource: source, weeks: GEN7_AIRDROP_WEEKS };
}

/**
 * The gen-7 pot's wiring + pre-authorization calls that chain state still lacks, in the setup script's order
 * (wiring, then the authorizations week by week). Generated by make-airdrop-setup-calls.mjs (`--wiring gen7
 * --only gen7`) at the current block time.
 */
export async function planGen7AirdropCalls(opts: { chainId: number; vault: string; setup: Gen7AirdropSetup }): Promise<PlannedCall[]> {
  const { airdropSetupCalls } = await esm("scripts/make-airdrop-setup-calls.mjs");
  const nowSec = Number((await ethers.provider.getBlock("latest"))!.timestamp);
  const all: any[] = airdropSetupCalls({
    chainId: opts.chainId,
    weeks: opts.setup.weeks,
    now: new Date(nowSec * 1000),
    pots: [{ pot: GEN7_POT, vault: opts.vault, distributor: opts.setup.distributor, cap: BigInt(opts.setup.cap), operator: opts.setup.operator, wire: true }],
  });
  const vault = new ethers.Contract(opts.vault, COMMUNITY_VAULT_ABI, ethers.provider);
  const dist = distAt(opts.setup.distributor);
  const out: PlannedCall[] = [];
  for (const c of all) {
    if (c.fn === "setRewardDistributor" && same(await vault.rewardDistributor(), c.args[0])) continue;
    if (c.fn === "setAirdropOperator" && same(await vault.airdropOperator(), c.args[0])) continue;
    if (c.fn === "setBatchOperator" && same(await dist.batchOperator(), c.args[0])) continue;
    if (c.fn === "authorizeBatch") {
      const a = await dist.batchAuthorization(c.args[0]);
      if (a.authorized || a.consumed) continue;
    }
    out.push({ contract: c.contract, to: c.to, fn: c.fn, args: c.args, note: c.note ?? (c.fn === "setAirdropOperator" ? `= the main pot's operator (${opts.setup.operatorSource})` : "gen-7 airdrop pot") });
  }
  return out;
}

/** Read-back of the gen-7 pot after its batch: wiring and the authorized weeks (runner's own runway check). */
export async function readGen7AirdropPot(opts: { chainId: number; vault: string; setup: Gen7AirdropSetup; admin: string }) {
  const vault = new ethers.Contract(opts.vault, COMMUNITY_VAULT_ABI, ethers.provider);
  const dist = distAt(opts.setup.distributor);
  const [rd, op, bo, owner, vAdmin] = await Promise.all([vault.rewardDistributor(), vault.airdropOperator(), dist.batchOperator(), dist.owner(), vault.admin()]);
  const wired = same(rd, opts.setup.distributor) && same(op, opts.setup.operator) && same(bo, opts.vault) && same(owner, opts.admin) && same(vAdmin, opts.admin);
  return { wired, rewardDistributor: rd, airdropOperator: op, batchOperator: bo, owner };
}

