/**
 * The gen-7 airdrop pot in the gen-7 release tooling (founder, 2026-10-08: two airdrop pots per EVM chain, the
 * gen-6 "main" one and a "gen7" one, everything automated; docs/claude/payouts-and-rewards.md "two pots").
 *
 * The gen-7 TreasuryRouterV4 has its own CommunityRewardsVault (one router per vault), so the gen-7 pot needs its
 * own airdrop RewardDistributor: `batchOperator` is a single address and `createBatch` is onlyOwnerOrBatchOperator,
 * so one distributor serves one vault (the gen-7 HOLDER distributor's operator is the CreatorRewardsVaultV2, so it
 * cannot be reused either).
 *
 * Deploy (deployer): `new RewardDistributor(initialOwner = admin)`; the admin is the Safe on 56/4663, the deployer
 * on 97/46630.
 * Admin calls (generated by scripts/make-airdrop-setup-calls.mjs, imported, so the batch ids are the runner's own
 * weeklyContractBatchId(chainId, epochId, program, "gen7")):
 *   CommunityRewardsVault(gen-7).setRewardDistributor(gen-7 airdrop distributor)
 *   CommunityRewardsVault(gen-7).setAirdropOperator(operator)   -- the main vault's airdropOperator(), read on chain
 *   RewardDistributor(gen-7 airdrop).setBatchOperator(gen-7 CommunityRewardsVault)
 *   RewardDistributor(gen-7 airdrop).authorizeBatch(id, cap, weekEnd, weekEnd + 6 d) x 12 weeks x {trader, creator}
 * Cap per batch: the main pot's current authorization (the main distributor's latest batchAuthorization.maxAmount
 * on chain, else the last authorizeBatch on that distributor in the repo's Safe batches), GEN7_AIRDROP_CAP
 * (native units, e.g. "5") overrides. GEN7_AIRDROP_OPERATOR overrides the operator.
 *
 * Every planner here returns only the calls chain state still lacks, so a rebuilt batch never repeats a done call.
 *
 * `runGen7AirdropWeek` rehearses one weekly draw of the gen-7 pot on a fork with the runner's own modules:
 * potRun.runPot (draw, materialize, fund, claim-open) over a fake DB client, chain.mjs resolvePoolWei and
 * ensureOnChainBatch against the fork. With no operator key in the environment the runner funds through its
 * funding-executor request (REWARD_FUNDING_EXECUTOR_URL); here that executor is local and sends
 * CommunityRewardsVault.fundAirdropBatch from the signer the caller passes (the impersonated airdrop operator on a
 * fork). chain.mjs reads the chain over HTTP, so a local JSON-RPC proxy forwards its calls to hardhat's provider
 * (works for anvil forks and the in-process hardhat fork alike).
 */
