  mp.market_role as "marketRole",
  mp.venue,
  mp.fee_tier as "feeTier",
  mp.router_address as "routerAddress",
  mp.factory_address as "factoryAddress",
  mp.verified,
  mp.trading_enabled as "tradingEnabled",
  mp.indexing_enabled as "indexingEnabled",
  mp.oracle_feed_address as "oracleFeedAddress",
  mp.market_policy_version as "marketPolicyVersion",
