  (base_decimals is null or base_decimals between 0 and 36)
  and (quote_decimals is null or quote_decimals between 0 and 36)
);

-- Normalize trades. Legacy native_amount_raw/price_bnb remain populated for
-- historical/native clients. Stock-market writers must write quote_* fields and
-- must not pretend a Stock Token amount is native ETH.
alter table public.dex_trades
  add column if not exists base_amount_raw text,
  add column if not exists quote_amount_raw text,
  add column if not exists base_amount numeric,
  add column if not exists quote_amount numeric,
  add column if not exists price_quote numeric,
  add column if not exists quote_asset_type text,
  add column if not exists quote_token_address text,
  add column if not exists volume_usd numeric,
  add column if not exists reference_price_usd numeric,
  add column if not exists reference_price_updated_at timestamptz;

update public.dex_trades t
set base_amount_raw=coalesce(t.base_amount_raw,t.token_amount_raw),
    quote_amount_raw=coalesce(t.quote_amount_raw,t.native_amount_raw),
    base_amount=coalesce(t.base_amount,t.token_amount),
    quote_amount=coalesce(t.quote_amount,t.native_amount),
    price_quote=coalesce(t.price_quote,t.price_bnb),
    quote_asset_type=coalesce(nullif(t.quote_asset_type,''),'WRAPPED_NATIVE'),
    quote_token_address=coalesce(
      nullif(t.quote_token_address,''),
      (select dp.wrapped_native_address
         from public.dex_pools dp
        where dp.chain_id=t.chain_id and lower(dp.pair_address)=lower(t.pair_address)
        limit 1)
    )
where t.chain_id in (4663,46630);

alter table public.dex_trades drop constraint if exists dex_trades_quote_asset_type_valid;
alter table public.dex_trades add constraint dex_trades_quote_asset_type_valid check(
  quote_asset_type is null or quote_asset_type=any(array['WRAPPED_NATIVE','STOCK_TOKEN','OTHER']::text[])
);
alter table public.dex_trades drop constraint if exists dex_trades_pair_raw_amounts_valid;
alter table public.dex_trades add constraint dex_trades_pair_raw_amounts_valid check(
  (base_amount_raw is null or base_amount_raw~'^[0-9]+$')
  and (quote_amount_raw is null or quote_amount_raw~'^[0-9]+$')
);

-- Backfill the pair registry from already accepted Robinhood direct-native pools.
insert into public.market_pairs(
  chain_id,campaign_address,pool_address,base_token_address,quote_token_address,
  base_decimals,quote_decimals,quote_asset_type,market_role,venue,fee_tier,
  router_address,factory_address,verified,trading_enabled,indexing_enabled,
  oracle_feed_address,market_policy_version,reserve_base_raw,reserve_quote_raw,
  last_verified_at,created_at,updated_at
)
select
  dp.chain_id,dp.campaign_address,dp.pair_address,
  coalesce(nullif(dp.base_token_address,''),dp.token_address),
  coalesce(nullif(dp.quote_token_address,''),dp.wrapped_native_address),
  dp.base_decimals,dp.quote_decimals,
  coalesce(nullif(dp.quote_asset_type,''),'WRAPPED_NATIVE'),
  coalesce(nullif(dp.market_role,''),'CANONICAL_NATIVE'),
  'robinhood_v3',
  case when dp.fee_bps is null then null else dp.fee_bps*100 end,
  dp.router_address,dp.factory_address,
  coalesce(cms.pool_verified,false),
  dp.support_enabled and dp.indexing_enabled and coalesce(cms.pool_verified,false),
  dp.indexing_enabled,
  dp.oracle_feed_address,
  coalesce(dp.market_policy_version,'robinhood_market_v1'),
  coalesce(dp.reserve_base_raw,dp.reserve_token_raw),
  coalesce(dp.reserve_quote_raw,dp.reserve_native_raw),
  cms.last_verified_at,
  dp.created_at,now()
from public.dex_pools dp
left join public.campaign_market_state cms
  on cms.chain_id=dp.chain_id and lower(cms.campaign_address)=lower(dp.campaign_address)
where dp.chain_id in (4663,46630)
on conflict(chain_id,lower(pool_address)) do nothing;

