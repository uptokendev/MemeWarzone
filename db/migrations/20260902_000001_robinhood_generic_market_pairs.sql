-- Robinhood Stock Battlefield: additive generic market-pair foundation.
--
-- This migration deliberately preserves the legacy native-oriented columns used by
-- existing BNB/Robinhood readers while introducing explicit base/quote semantics.
-- Existing MEME/WETH Robinhood markets are backfilled as CANONICAL_NATIVE. Future
-- MEME/Stock Token graduations must register CANONICAL_STOCK rows explicitly.

create table if not exists public.market_pairs (
  id bigint generated by default as identity primary key,
  chain_id integer not null,
  campaign_address text not null,
  pool_address text not null,
  base_token_address text not null,
  quote_token_address text not null,
  base_decimals integer,
  quote_decimals integer,
  quote_asset_type text not null,
  market_role text not null,
  venue text not null,
  fee_tier integer,
  router_address text,
  factory_address text,
  verified boolean not null default false,
  trading_enabled boolean not null default false,
  indexing_enabled boolean not null default true,
  oracle_feed_address text,
  market_policy_version text,
  reserve_base_raw text,
  reserve_quote_raw text,
  last_verified_at timestamptz,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint market_pairs_distinct_assets check(lower(base_token_address)<>lower(quote_token_address)),
  constraint market_pairs_quote_asset_type_valid check(
    quote_asset_type=any(array['WRAPPED_NATIVE','STOCK_TOKEN','OTHER']::text[])
  ),
  constraint market_pairs_market_role_valid check(
    market_role=any(array['CANONICAL_NATIVE','CANONICAL_STOCK','ADDITIONAL','EXTERNAL']::text[])
  ),
  constraint market_pairs_decimals_valid check(
    (base_decimals is null or base_decimals between 0 and 36)
    and (quote_decimals is null or quote_decimals between 0 and 36)
  ),
  constraint market_pairs_fee_tier_valid check(fee_tier is null or fee_tier between 0 and 1000000),
  constraint market_pairs_reserve_base_raw_valid check(reserve_base_raw is null or reserve_base_raw~'^[0-9]+$'),
  constraint market_pairs_reserve_quote_raw_valid check(reserve_quote_raw is null or reserve_quote_raw~'^[0-9]+$')
);

create unique index if not exists market_pairs_pool_uidx
  on public.market_pairs(chain_id,lower(pool_address));

create unique index if not exists market_pairs_canonical_campaign_uidx
  on public.market_pairs(chain_id,lower(campaign_address))
  where market_role in ('CANONICAL_NATIVE','CANONICAL_STOCK');

create index if not exists market_pairs_campaign_idx
  on public.market_pairs(chain_id,lower(campaign_address),updated_at desc);

create index if not exists market_pairs_quote_asset_idx
  on public.market_pairs(chain_id,lower(quote_token_address),quote_asset_type,trading_enabled,indexing_enabled);

comment on table public.market_pairs is
  'Pair-level market registry. Canonical lifecycle remains in campaign_market_state; this table defines explicit base/quote market semantics.';
comment on column public.market_pairs.quote_asset_type is
  'WRAPPED_NATIVE, STOCK_TOKEN, or OTHER. Never infer Stock Token identity from symbol alone.';
comment on column public.market_pairs.market_role is
  'V1 campaigns have one canonical market: CANONICAL_NATIVE or CANONICAL_STOCK.';

