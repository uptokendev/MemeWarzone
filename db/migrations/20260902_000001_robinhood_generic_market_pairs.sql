-- Existing Robinhood V3 rows are the accepted direct MEME/WETH markets. We only
-- backfill chain 4663/46630 here; other chains keep their historical semantics.
update public.dex_pools
set base_token_address=coalesce(nullif(base_token_address,''),token_address),
    quote_token_address=coalesce(nullif(quote_token_address,''),wrapped_native_address),
    quote_asset_type=coalesce(nullif(quote_asset_type,''),'WRAPPED_NATIVE'),
    market_role=coalesce(nullif(market_role,''),'CANONICAL_NATIVE'),
    reserve_base_raw=coalesce(reserve_base_raw,reserve_token_raw),
    reserve_quote_raw=coalesce(reserve_quote_raw,reserve_native_raw)
where chain_id in (4663,46630);

